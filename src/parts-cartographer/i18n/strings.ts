export function membersPhrase(n: number, lang: Lang): string {
  if (lang === 'en') return `${n} member${n === 1 ? '' : 's'}`;
  const m10 = n % 10, m100 = n % 100;
  const w = (m10 === 1 && m100 !== 11) ? 'участник'
    : (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) ? 'участника' : 'участников';
  return `${n} ${w}`;
}

